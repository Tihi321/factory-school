import React, { useState } from 'react';
import { FACTORY_BLUEPRINT_ITEMS } from '../data/subjects';
import { useFactoryStore } from '../store/useFactoryStore';
import { BlueprintChecklistItem } from '../types/curriculum';
import {
  CheckSquare,
  Square,
  Copy,
  Download,
  Check,
  FileCode,
  Sparkles,
  Layers,
  ShieldCheck,
  Filter,
} from 'lucide-react';
import clsx from 'clsx';
import { motion, AnimatePresence } from 'framer-motion';

type CategoryFilter =
  | 'All'
  | 'Codebase Design'
  | 'Verification Loops'
  | 'System-1 & Swarms'
  | 'Gates & Production Watchers';

export const BlueprintBuilder: React.FC = () => {
  const { checkedBlueprintItems, toggleBlueprintItem, xp } = useFactoryStore();
  const [selectedCategory, setSelectedCategory] = useState<CategoryFilter>('All');
  const [copied, setCopied] = useState(false);
  const [copiedArtifact, setCopiedArtifact] = useState<string | null>(null);

  const categories: CategoryFilter[] = [
    'All',
    'Codebase Design',
    'Verification Loops',
    'System-1 & Swarms',
    'Gates & Production Watchers',
  ];

  const filteredItems = FACTORY_BLUEPRINT_ITEMS.filter((item) => {
    if (selectedCategory === 'All') return true;
    return item.category === selectedCategory;
  });

  const readinessScore = Math.round(
    (checkedBlueprintItems.length / FACTORY_BLUEPRINT_ITEMS.length) * 100
  );

  // Generate full markdown document
  const generateMarkdownBlueprint = (): string => {
    const timestamp = new Date().toISOString().split('T')[0];
    let md = `# SOFTWARE FACTORY BLUEPRINT
*Generated by Agentic Coding School — The Software Factory Engineer*
*Date: ${timestamp} | Readiness Score: ${readinessScore}% (${checkedBlueprintItems.length}/${FACTORY_BLUEPRINT_ITEMS.length} Invariants Implemented)*

---

## 🎯 Executive Summary
This blueprint defines the architecture, automated verification membranes, and back-pressure loops required to transition a codebase from manual, high-fatigue LLM prompt-babysitting into an autonomous Software Factory.

---

`;

    const grouped: Record<string, BlueprintChecklistItem[]> = {};
    FACTORY_BLUEPRINT_ITEMS.forEach((item) => {
      if (!grouped[item.category]) grouped[item.category] = [];
      grouped[item.category].push(item);
    });

    for (const [category, items] of Object.entries(grouped)) {
      md += `### ## ${category.toUpperCase()}\n\n`;
      items.forEach((item) => {
        const isChecked = checkedBlueprintItems.includes(item.id);
        const checkMark = isChecked ? '[x]' : '[ ]';
        md += `- ${checkMark} **${item.title}**\n`;
        md += `  - **Description**: ${item.description}\n`;
        md += `  - **Target Artifact**: \`${item.artifactToCreate}\`\n`;
        md += `  - **Status**: ${isChecked ? 'COMPLETE' : 'PENDING'}\n\n`;
      });
    }

    md += `---
## 🛡️ Next Steps
1. Create the pending invariant files in your repository root.
2. Ensure continuous CI enforces all invariant contracts before any human code review.
3. Keep biological attention reserved strictly for specification and system design.
`;
    return md;
  };

  const handleCopyMarkdown = () => {
    const md = generateMarkdownBlueprint();
    navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdownBlueprint();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'SOFTWARE_FACTORY_BLUEPRINT.md';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleCopyArtifactPath = (path: string, e: React.MouseEvent) => {
    e.stopPropagation();
    navigator.clipboard.writeText(path);
    setCopiedArtifact(path);
    setTimeout(() => setCopiedArtifact(null), 2000);
  };

  return (
    <div className="space-y-8 pb-16">
      {/* Blueprint Header Banner */}
      <div className="rounded-3xl border border-line bg-card p-6 sm:p-10 shadow-xl">
        <div className="flex flex-col lg:flex-row lg:items-center lg:justify-between gap-6">
          <div className="max-w-2xl">
            <div className="inline-flex items-center gap-2 rounded-full border border-accent-line bg-accent-wash px-3 py-1 font-mono text-xs font-semibold text-accent">
              <ShieldCheck className="h-3.5 w-3.5" />
              <span>THE 12 FACTORY INVARIANTS</span>
            </div>
            <h1 className="mt-3 font-serif text-3xl font-bold text-fg sm:text-4xl">
              My Software Factory Blueprint
            </h1>
            <p className="mt-2 text-sm text-fg-muted leading-relaxed">
              Check off each architecture pattern as you implement it in your own repositories.
              Checking an item awards <strong className="text-accent">+30 XP</strong> and simulates
              compute hours saved.
            </p>
          </div>

          {/* Readiness Score Card */}
          <div className="rounded-2xl border border-line bg-band p-5 flex flex-col items-center justify-center min-w-[220px]">
            <span className="font-mono text-xs uppercase text-fg-subtle">
              Factory Readiness
            </span>
            <div className="mt-1 flex items-baseline gap-1 font-mono text-4xl font-extrabold text-accent">
              {readinessScore}%
            </div>
            <div className="mt-1 text-xs text-fg-muted">
              {checkedBlueprintItems.length} of {FACTORY_BLUEPRINT_ITEMS.length} Invariants Live
            </div>
            <div className="mt-3 h-2 w-full overflow-hidden rounded-full bg-card">
              <div
                className="h-full bg-accent transition-all duration-500"
                style={{ width: `${readinessScore}%` }}
              />
            </div>
          </div>
        </div>

        {/* Action Buttons for Export */}
        <div className="mt-8 flex flex-wrap items-center gap-3 border-t border-line pt-6">
          <button
            onClick={handleCopyMarkdown}
            className="flex items-center gap-2 rounded-xl bg-accent px-4 py-2.5 text-xs font-bold text-accent-ink hover:bg-accent-hover transition shadow-sm"
          >
            {copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" />}
            <span>{copied ? 'Copied to Clipboard!' : 'Copy SOFTWARE_FACTORY_BLUEPRINT.md'}</span>
          </button>

          <button
            onClick={handleDownloadMarkdown}
            className="flex items-center gap-2 rounded-xl border border-line bg-band px-4 py-2.5 text-xs font-medium text-fg hover:border-line-strong hover:bg-card transition"
          >
            <Download className="h-4 w-4 text-accent" />
            <span>Download Markdown File</span>
          </button>

          <span className="font-mono text-xs text-fg-subtle ml-auto">
            Ready to commit directly to your repository root
          </span>
        </div>
      </div>

      {/* Category Filter Pills */}
      <div className="flex flex-wrap items-center gap-2">
        <span className="flex items-center gap-1.5 text-xs font-mono text-fg-subtle mr-2">
          <Filter className="h-3.5 w-3.5" /> Filter Category:
        </span>
        {categories.map((cat) => {
          const isSelected = selectedCategory === cat;
          return (
            <button
              key={cat}
              onClick={() => setSelectedCategory(cat)}
              className={clsx(
                'rounded-lg px-3 py-1.5 text-xs font-medium transition',
                isSelected
                  ? 'border border-accent-line bg-accent-wash text-accent font-semibold'
                  : 'border border-line bg-card text-fg-muted hover:text-fg hover:border-line-strong'
              )}
            >
              {cat}
            </button>
          );
        })}
      </div>

      {/* Checklist Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {filteredItems.map((item) => {
          const isChecked = checkedBlueprintItems.includes(item.id);
          const isCopiedThis = copiedArtifact === item.artifactToCreate;

          return (
            <div
              key={item.id}
              onClick={() => toggleBlueprintItem(item.id)}
              className={clsx(
                'cursor-pointer rounded-2xl border p-5 transition-all select-none',
                isChecked
                  ? 'border-good/50 bg-good/5 shadow-sm'
                  : 'border-line bg-card hover:border-line-strong'
              )}
            >
              <div className="flex items-start justify-between gap-3">
                <div className="flex items-start gap-3">
                  <button
                    type="button"
                    className="mt-0.5 text-fg hover:text-accent transition"
                    onClick={(e) => {
                      e.stopPropagation();
                      toggleBlueprintItem(item.id);
                    }}
                  >
                    {isChecked ? (
                      <CheckSquare className="h-5 w-5 text-good" />
                    ) : (
                      <Square className="h-5 w-5 text-fg-subtle" />
                    )}
                  </button>

                  <div>
                    <span
                      className={clsx(
                        'inline-block rounded px-2 py-0.5 font-mono text-[10px] font-bold uppercase',
                        isChecked
                          ? 'bg-good/20 text-good'
                          : 'bg-band text-fg-subtle'
                      )}
                    >
                      {item.category}
                    </span>

                    <h3
                      className={clsx(
                        'mt-1 font-serif text-base font-bold transition',
                        isChecked ? 'text-fg line-through opacity-80' : 'text-fg'
                      )}
                    >
                      {item.title}
                    </h3>
                  </div>
                </div>

                <span className="font-mono text-[10px] text-accent font-bold">
                  {isChecked ? 'DONE (+30 XP)' : '+30 XP'}
                </span>
              </div>

              <p className="mt-2 text-xs text-fg-muted leading-relaxed pl-8">
                {item.description}
              </p>

              {/* Target Artifact Path pill */}
              <div className="mt-4 flex items-center justify-between rounded-lg border border-line bg-band px-3 py-1.5 text-xs font-mono ml-8">
                <div className="flex items-center gap-2 overflow-hidden text-fg-subtle text-[11px]">
                  <FileCode className="h-3.5 w-3.5 text-accent shrink-0" />
                  <span className="truncate">{item.artifactToCreate}</span>
                </div>

                <button
                  onClick={(e) => handleCopyArtifactPath(item.artifactToCreate, e)}
                  title="Copy path to clipboard"
                  className="ml-2 text-fg-subtle hover:text-accent transition shrink-0"
                >
                  {isCopiedThis ? (
                    <span className="text-[10px] text-good font-bold">Copied!</span>
                  ) : (
                    <Copy className="h-3.5 w-3.5" />
                  )}
                </button>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
